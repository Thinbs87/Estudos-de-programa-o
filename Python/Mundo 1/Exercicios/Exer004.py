Resposta = input("Digite uma resposta: ")
print('O tipo primitivo da variavel digitada é: ', type(Resposta))
print('Só tem espaços? ', Resposta.isspace())
print('É um número? ', Resposta.isnumeric())
print('É alfabético? ', Resposta.isalpha())
print('É alfanumérico? ', Resposta.isalnum())
print('Está em maiúsculas? ', Resposta.isupper())
print('Está em minúsculas? ', Resposta.islower())
print('Está capitalizada? ', Resposta.istitle())
print('Está em caixa de título? ', Resposta.istitle())
